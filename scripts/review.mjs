// Writes sites/<slug>/REVIEW.md from site.json and notes.md: what a human must check before the preview link
// goes to the business. Regenerate after every site.json change; never edit REVIEW.md by hand.
// Usage: node scripts/review.mjs <slug>
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { PREVIEWS_ORIGIN } from '../template/config.ts';
import { analyseSite } from './lib/analyse.mjs';
import { fail, loadSite } from './lib/sites.mjs';

const DAY_LABELS = { mon: 'Mon', tue: 'Tue', wed: 'Wed', thu: 'Thu', fri: 'Fri', sat: 'Sat', sun: 'Sun' };

const [slug] = process.argv.slice(2);
if (!slug) fail('Usage: node scripts/review.mjs <slug>');
const { site, siteDir } = loadSite(slug);
const notesFile = path.join(siteDir, 'notes.md');
const notes = existsSync(notesFile) ? readFileSync(notesFile, 'utf8').trim() : '';
const today = new Date().toISOString().slice(0, 10);

const { ext, facts, missing, services, generic, checkFirst, singleSource, confidence } = analyseSite(site);

const lines = [
  `# Review: ${site.business.name} (\`${slug}\`)`,
  '',
  `Preview: ${PREVIEWS_ORIGIN}/${slug}/ · expires ${site.previewExpires ?? '–'} · confidence ${confidence}/100`,
  '',
  `Generated by \`pnpm review ${slug}\` on ${today}. Fix facts in site.json, then regenerate: never edit this file.`,
  '',
  'Before the link goes to the business: open each source under **Check first** and **High confidence, one source**, confirm the value, then read **Copy** against **Facts**.',
  '',
  '## Check first',
  '',
  ...(checkFirst.length || generic.length
    ? [
        ...checkFirst.map((f) => `- [ ] **${f.path}** · ${f.source.confidence} · ${show(f)} · ${links(f.source)}${note(f.source)}`),
        ...(generic.length
          ? [`- [ ] **${ext}.services** · generic (implied by the sub-type, not found in research): ${generic.join(', ')}`]
          : []),
      ]
    : ['Nothing: every fact is high confidence.']),
  '',
  '## High confidence, one source',
  '',
  ...(singleSource.length
    ? singleSource.map((f) => `- [ ] **${f.path}** · ${show(f)} · ${links(f.source)}${note(f.source)}`)
    : ['None.']),
  '',
  '## Copy',
  '',
  'Every claim here must match a fact below, and services named here must not be generic (see the tone guide for claims that need a source).',
  '',
  ...copyLines(),
  '',
  '## Facts',
  '',
  '| Fact | Value | Confidence | Sources |',
  '|---|---|---|---|',
  ...facts.map((f) => `| ${f.path} | ${show(f).replaceAll('|', '/')} | ${f.source?.confidence ?? '–'} | ${f.source ? links(f.source) : 'generic'} |`),
  '',
  '## Not found',
  '',
  missing.length ? missing.join(', ') : 'Nothing missing.',
  '',
  '## Agent notes',
  '',
  notes || 'None.',
  '',
];
writeFileSync(path.join(siteDir, 'REVIEW.md'), lines.join('\n'));
console.log(`Wrote sites/${slug}/REVIEW.md: ${checkFirst.length + (generic.length ? 1 : 0)} to check first, ${singleSource.length} high-confidence with one source.`);

function show({ path: factPath, value }) {
  if (factPath === 'business.hours') {
    return Object.entries(DAY_LABELS)
      .filter(([day]) => value[day])
      .map(([day, label]) => `${label} ${value[day].length ? value[day].map((i) => `${i.open}–${i.close}`).join(', ') : 'closed'}`)
      .join('; ');
  }
  if (factPath === 'business.rating') return `${value.value}★ · ${value.count} reviews`;
  if (factPath === 'business.address') return `${value.street}, ${value.postalCode} ${value.city} (${value.province})`;
  if (factPath.endsWith('.services')) return value.map((s) => (s.generic ? `${s.name} (generic)` : s.name)).join(', ');
  if (Array.isArray(value)) return value.join(', ');
  if (typeof value === 'object') return JSON.stringify(value);
  return String(value);
}

function links(source) {
  return source.urls.length ? source.urls.map((u, i) => `[${i + 1}](${u})`).join(' ') : 'confirmed by client';
}

function note(source) {
  return source.note ? ` · _${source.note}_` : '';
}

function copyLines() {
  const entries = [
    ['headline', site.copy.headline],
    ['tagline', site.copy.tagline],
    ['about', site.copy.about],
    ['seo.title', site.seo.title],
    ['seo.description', site.seo.description],
    ...services.filter((s) => s.description).map((s) => [`service: ${s.name}`, s.description]),
  ].filter(([, text]) => text);
  if (!entries.length) return ['No custom copy: the template defaults are used.'];
  return entries.flatMap(([label, text]) => [`**${label}**`, '', ...text.split('\n').map((l) => `> ${l}`), '']);
}
